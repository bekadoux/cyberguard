// Package sessionstore adapts SCS persistence so a stale request cannot recreate
// a token deleted by logout or rotation. SCS still owns tokens and serialization.
package sessionstore

import (
	"context"
	"errors"
	"sync"
	"time"

	"github.com/alexedwards/scs/v2"
)

var ErrRevoked = errors.New("session no longer exists or has expired")

var errRequestContext = errors.New("session persistence requires request context")

// Backend must create without overwriting and refresh without inserting. Refresh
// must return ErrRevoked if the token no longer exists or has expired; checking
// existence separately from an upsert does not satisfy this contract.
type Backend interface {
	FindCtx(context.Context, string) ([]byte, bool, error)
	DeleteCtx(context.Context, string) error
	CreateCtx(context.Context, string, []byte, time.Time) error
	RefreshCtx(context.Context, string, []byte, time.Time) error
}

type Store struct{ backend Backend }

var _ scs.CtxStore = (*Store)(nil)

func New(backend Backend) *Store { return &Store{backend: backend} }

type requestKey struct{}
type requestState struct {
	mu     sync.Mutex
	tokens map[string]bool
}

// WithRequest must run once outside SCS LoadAndSave. State belongs to one request,
// never to a process-wide map. Tokens here are SCS's hashed persistence identifiers.
func WithRequest(ctx context.Context) context.Context {
	return context.WithValue(ctx, requestKey{}, &requestState{tokens: make(map[string]bool)})
}

func (s *Store) FindCtx(ctx context.Context, token string) ([]byte, bool, error) {
	state, ok := ctx.Value(requestKey{}).(*requestState)
	if !ok {
		return nil, false, errRequestContext
	}
	state.mu.Lock()
	defer state.mu.Unlock()
	data, found, err := s.backend.FindCtx(ctx, token)
	if err == nil && found {
		state.tokens[token] = true
	}
	return data, found, err
}

func (s *Store) CommitCtx(ctx context.Context, token string, data []byte, expiry time.Time) error {
	state, ok := ctx.Value(requestKey{}).(*requestState)
	if !ok {
		return errRequestContext
	}
	state.mu.Lock()
	defer state.mu.Unlock()
	if state.tokens[token] {
		return s.backend.RefreshCtx(ctx, token, data, expiry)
	}
	// An unseen commit token was newly generated by SCS (including RenewToken),
	// not copied from the browser. INSERT must reject collisions, not upsert.
	if err := s.backend.CreateCtx(ctx, token, data, expiry); err != nil {
		return err
	}
	state.tokens[token] = true
	return nil
}

func (s *Store) DeleteCtx(ctx context.Context, token string) error {
	// Deliberately retain the request's knowledge of deleted tokens: any stale
	// commit for one must still be an UPDATE, never a new INSERT.
	return s.backend.DeleteCtx(ctx, token)
}

// SCS uses CtxStore; reject accidental non-context access rather than bypassing
// the request-local distinction between creation and refresh.
func (s *Store) Find(string) ([]byte, bool, error)      { return nil, false, errRequestContext }
func (s *Store) Commit(string, []byte, time.Time) error { return errRequestContext }
func (s *Store) Delete(string) error                    { return errRequestContext }
